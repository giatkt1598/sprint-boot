export const phosphorIcons = (weight: IconWeight): IconSet => {
  const set: IconSet = {};
  for (const [name, Drawn] of Object.entries(drawn)) {
    function PhosphorIcon({ size = 24, ...props }: IconProps) {
      return <Drawn size={size} weight={weight} {...svgAttributes(props)} />;
    }
    set[name as IconName] = PhosphorIcon;
  }
  return set;
};
