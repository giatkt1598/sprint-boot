export const iconoirIcons = (stroke: number): IconSet => {
  const set: IconSet = {};
  for (const [name, Drawn] of Object.entries(drawn)) {
    function IconoirIcon({ size = 24, ...props }: IconProps) {
      return <Drawn width={size} height={size} strokeWidth={stroke} {...svgAttributes(props)} />;
    }
    set[name as IconName] = IconoirIcon;
  }
  return set;
};
