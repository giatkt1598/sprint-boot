export const heroIcons = (): IconSet => {
  const set: IconSet = {};
  for (const [name, Drawn] of Object.entries(drawn)) {
    function HeroIcon({ size = 24, ...props }: IconProps) {
      return <Drawn width={size} height={size} strokeWidth={1.5} aria-hidden {...svgAttributes(props)} />;
    }
    set[name as IconName] = HeroIcon;
  }
  return set;
};
