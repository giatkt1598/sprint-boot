export const tablerIcons = (stroke: number): IconSet => {
  const set: IconSet = {};
  for (const [name, Drawn] of Object.entries(drawn)) {
    function TablerIcon({ size = 24, ...props }: IconProps) {
      return <Drawn size={size} stroke={stroke} {...svgAttributes(props)} />;
    }
    set[name as IconName] = TablerIcon;
  }
  return set;
};
